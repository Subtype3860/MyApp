-- Run inside an explicit transaction, after backing up public.car_f.
-- Keeps the CSV source and a materialized before-migration snapshot.
DO $migration$
DECLARE
    source_oid oid := to_regclass('public.car_f');
    source_kind "char";
    expected_fingerprint text := current_setting('myapp.car_f_expected_fingerprint', true);
    actual_fingerprint text;
BEGIN
    IF source_oid IS NULL THEN
        RAISE EXCEPTION 'public.car_f does not exist';
    END IF;
    SELECT relkind INTO source_kind FROM pg_class WHERE oid = source_oid;
    IF source_kind = 'r' THEN
        RAISE NOTICE 'public.car_f is already a regular table; nothing was changed';
        RETURN;
    END IF;
    IF source_kind <> 'f' THEN
        RAISE EXCEPTION 'Expected a foreign table, got relation kind %', source_kind;
    END IF;
    IF to_regclass('public.car_f_external_20261011') IS NOT NULL OR
       to_regclass('public.car_f_snapshot_20261011') IS NOT NULL THEN
        RAISE EXCEPTION 'Backup names already exist; migration aborted';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_depend WHERE refclassid = 'pg_class'::regclass AND refobjid = source_oid AND deptype <> 'i') THEN
        RAISE EXCEPTION 'car_f has dependencies; inspect them before migrating';
    END IF;

    -- ALTER acquires the relation lock; rollback restores the original name on failure.
    ALTER FOREIGN TABLE public.car_f RENAME TO car_f_external_20261011;
    CREATE TABLE public.car_f_snapshot_20261011
        (LIKE public.car_f_external_20261011 INCLUDING ALL);
    INSERT INTO public.car_f_snapshot_20261011 SELECT * FROM public.car_f_external_20261011;

    IF EXISTS (SELECT 1 FROM public.car_f_snapshot_20261011 WHERE id IS NULL) OR
       EXISTS (SELECT id FROM public.car_f_snapshot_20261011 GROUP BY id HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'Existing IDs must be populated and unique; no data was changed';
    END IF;
    SELECT md5(COALESCE(string_agg(row_to_json(t)::text, E'\n' ORDER BY id), ''))
      INTO actual_fingerprint FROM public.car_f_snapshot_20261011 AS t;
    IF expected_fingerprint IS NOT NULL AND expected_fingerprint <> actual_fingerprint THEN
        RAISE EXCEPTION 'Source changed after backup; take a new backup before retrying';
    END IF;

    CREATE TABLE public.car_f (LIKE public.car_f_snapshot_20261011 INCLUDING ALL);
    INSERT INTO public.car_f SELECT * FROM public.car_f_snapshot_20261011;
    ALTER TABLE public.car_f ALTER COLUMN id SET NOT NULL;
    ALTER TABLE public.car_f ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE public.car_f ADD CONSTRAINT car_f_pkey PRIMARY KEY (id);
    PERFORM setval(pg_get_serial_sequence('public.car_f', 'id'),
        GREATEST(COALESCE(max(id), 1), 1), COALESCE(max(id), 0) >= 1) FROM public.car_f;

    IF EXISTS (
        (SELECT * FROM public.car_f EXCEPT ALL SELECT * FROM public.car_f_snapshot_20261011)
        UNION ALL
        (SELECT * FROM public.car_f_snapshot_20261011 EXCEPT ALL SELECT * FROM public.car_f)
    ) THEN
        RAISE EXCEPTION 'Copy verification failed; migration rolled back';
    END IF;
    COMMENT ON TABLE public.car_f IS 'Local editable vehicle import catalogue; migrated from car.csv on 2026-10-11';
    COMMENT ON TABLE public.car_f_snapshot_20261011 IS 'Materialized pre-migration snapshot; preserve for rollback';
    COMMENT ON FOREIGN TABLE public.car_f_external_20261011 IS 'Original read-only CSV source; preserve for rollback';
END
$migration$;
